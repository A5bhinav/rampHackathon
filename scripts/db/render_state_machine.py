#!/usr/bin/env python3
"""Redraw the case state machine from app.case_transitions.

Usage: DATABASE_URL=... render_state_machine.py docs/state-machine.md

The table is the source of truth (ADR-1); this file is a picture of it. CI runs this after
the migrations and fails if the committed Markdown differs.
"""
import os
import subprocess
import sys

QUERY = """
select coalesce(from_state::text, '(new)'), event_type, actor_kind::text, guard_key, to_state::text, description
  from app.case_transitions
 order by from_state nulls first, event_type, guard_key
"""


def main() -> int:
    out_path = sys.argv[1] if len(sys.argv) > 1 else "docs/state-machine.md"
    url = os.environ["DATABASE_URL"]
    raw = subprocess.run(
        ["psql", "-X", "-At", "-F", "\t", url, "-c", QUERY],
        check=True, capture_output=True, text=True,
    ).stdout
    rows = [line.split("\t") for line in raw.splitlines() if line]

    lines = [
        "# Case state machine",
        "",
        "Generated by `scripts/db/render_state_machine.py` from `app.case_transitions`. Do not edit by hand.",
        "",
        "Ten states. `released` is the only finished state. Every failure path ends in a state where the",
        "hold stays on. Moves marked **person** need a signed-in user; everything else is the system.",
        "",
        "```mermaid",
        "stateDiagram-v2",
    ]
    for frm, event, actor, guard, to, _ in rows:
        src = "[*]" if frm == "(new)" else frm
        label = event if guard == "always" else f"{event} [{guard}]"
        if actor == "person":
            label = f"{label} (person)"
        lines.append(f"    {src} --> {to}: {label}")
    lines.append("    released --> [*]")
    lines += ["```", "", "| From | Event | Who | Guard | To | Why |", "|---|---|---|---|---|---|"]
    for frm, event, actor, guard, to, desc in rows:
        who = "**person**" if actor == "person" else "system"
        lines.append(f"| {frm} | `{event}` | {who} | `{guard}` | {to} | {desc} |")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path} ({len(rows)} transitions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
